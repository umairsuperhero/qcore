import fs from "node:fs";
import { createRequire } from "node:module";
import os from "node:os";
import path from "node:path";

const require = createRequire(import.meta.url);
const playwrightPackage = process.env.QCORE_DEMO_PLAYWRIGHT_PACKAGE || "playwright";
const { chromium } = require(playwrightPackage);

const dashboardURL = process.env.QCORE_DASHBOARD_URL || "http://localhost:3000";
const outputDir = process.env.QCORE_DEMO_OUTPUT_DIR || "docs/outreach/assets";
const terminalLogPath = process.env.QCORE_DEMO_TERMINAL_LOG || path.join(outputDir, "qcore-demo-terminal.txt");
const evidencePath = process.env.QCORE_DEMO_EVIDENCE_JSON || path.join(outputDir, "qcore-demo-evidence.json");
const videoDir = path.join(outputDir, ".video");
const rawWebm = path.join(outputDir, "qcore-demo.webm");

fs.mkdirSync(outputDir, { recursive: true });
fs.mkdirSync(videoDir, { recursive: true });

const startedAt = new Date();
const platform = `${os.type()} ${os.release()} ${os.arch()}`;
const linuxNative = os.type() === "Linux";
const evidence = {
  schema: "qcore.demo_recording.v1",
  started_at: startedAt.toISOString(),
  dashboard_url: dashboardURL,
  platform,
  native_sctp_tun_claim: linuxNative,
  source: linuxNative
    ? "real QCore dashboard/simulator run on Linux; eligible for native SCTP/TUN evidence if run in the interop environment"
    : "real QCore dashboard/simulator run on non-Linux; do not cite as native SCTP/TUN evidence",
  beats: [],
};

function escapeHTML(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

